const monthNames = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December"
];

const weekDays = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];

function formatDate(date) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

function getMonthDays(year, month) {
  const firstDay = new Date(year, month, 1).getDay();
  const totalDays = new Date(year, month + 1, 0).getDate();
  const list = [];

  for (let i = 0; i < firstDay; i += 1) list.push(null);
  for (let day = 1; day <= totalDays; day += 1) list.push(day);

  return list;
}

function getJewishDate(date) {
  try {
    return new Intl.DateTimeFormat("en-u-ca-hebrew", {
      day: "numeric",
      month: "short"
    }).format(date);
  } catch {
    return "";
  }
}

function getTodayKey() {
  return formatDate(new Date());
}

function getLocalUploads() {
  try {
    if (typeof localStorage === "undefined") return {};
    return JSON.parse(localStorage.getItem("calendarUploads") || "{}");
  } catch {
    return {};
  }
}

function saveLocalUploads(data) {
  try {
    if (typeof localStorage !== "undefined") {
      localStorage.setItem("calendarUploads", JSON.stringify(data));
    }
  } catch {
    // Local storage can be blocked by the browser.
  }
}

function cleanJewishTitle(item) {
  const title = item.title || "";

  if (item.category === "parashat") {
    return title.startsWith("Parashat ") ? title.replace("Parashat ", "Parsha: ") : `Parsha: ${title}`;
  }

  return title;
}

function shouldShowJewishEvent(item) {
  if (!item || !item.date || !item.title) return false;

  const category = item.category || "";
  const subcat = item.subcat || "";

  if (category === "parashat") return true;
  if (category === "holiday") return true;
  if (category === "roshchodesh") return true;
  if (category === "omer") return false;
  if (category === "dafyomi") return false;
  if (category === "candles") return false;
  if (category === "havdalah") return false;
  if (!SHOW_MINOR_JEWISH_DATES && subcat === "minor") return false;

  return false;
}

function mapHebcalItems(items) {
  const mapped = {};

  (items || []).forEach((item) => {
    if (!shouldShowJewishEvent(item)) return;

    const dateKey = String(item.date || "").slice(0, 10);
    if (!dateKey) return;

    const event = {
      title: cleanJewishTitle(item),
      category: item.category || "holiday",
      yomTov: Boolean(item.yomtov)
    };

    if (!mapped[dateKey]) mapped[dateKey] = [];
    mapped[dateKey].push(event);
  });

  return mapped;
}

async function fetchJewishEvents(startDate, endDate) {
  const params = new URLSearchParams({
    cfg: "json",
    v: "1",
    start: startDate,
    end: endDate,
    maj: "on",
    min: "on",
    mod: "on",
    nx: "on",
    mf: "on",
    ss: "on",
    s: "on",
    c: "off",
    geo: "none",
    i: ISRAEL_CALENDAR ? "on" : "off",
    lg: "s"
  });

  const response = await fetch(`https://www.hebcal.com/hebcal?${params.toString()}`);
  if (!response.ok) throw new Error("Could not load Jewish calendar events");

  const data = await response.json();
  return mapHebcalItems(data.items || []);
}

function canUseSupabase() {
  return Boolean(SUPABASE_URL && SUPABASE_ANON_KEY);
}

function supabaseHeaders(extra = {}) {
  return {
    apikey: SUPABASE_ANON_KEY,
    Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
    ...extra
  };
}

async function readErrorText(response) {
  try {
    const text = await response.text();
    return text || `${response.status} ${response.statusText}`;
  } catch {
    return `${response.status} ${response.statusText}`;
  }
}

function getSetupSql() {
  return `create table if not exists calendar_uploads (
  id bigint generated by default as identity primary key,
  date date not null unique,
  file_name text not null,
  file_url text not null,
  file_type text,
  created_at timestamptz default now()
);`;
}

function makeSchemaError(details) {
  return new Error(`Supabase table setup needed. The table must have columns: date, file_name, file_url, file_type. Details: ${details}`);
}

async function supabaseSelectUploads(startDate, endDate) {
  const url = `${SUPABASE_URL}/rest/v1/${TABLE_NAME}?select=${DATE_COLUMN},file_name,file_url,file_type&${DATE_COLUMN}=gte.${startDate}&${DATE_COLUMN}=lte.${endDate}`;
  const response = await fetch(url, {
    headers: supabaseHeaders({ Accept: "application/json" })
  });

  if (!response.ok) {
    const details = await readErrorText(response);
    if (details.includes("42703") || details.includes("does not exist")) {
      throw makeSchemaError(details);
    }
    throw new Error(`Could not load uploads: ${details}`);
  }

  return response.json();
}

async function supabaseSelectToday(today) {
  const url = `${SUPABASE_URL}/rest/v1/${TABLE_NAME}?select=${DATE_COLUMN},file_name,file_url,file_type&${DATE_COLUMN}=eq.${today}&limit=1`;
  const response = await fetch(url, {
    headers: supabaseHeaders({ Accept: "application/json" })
  });

  if (!response.ok) {
    const details = await readErrorText(response);
    if (details.includes("42703") || details.includes("does not exist")) {
      throw makeSchemaError(details);
    }
    throw new Error(`Could not load today upload: ${details}`);
  }

  const rows = await response.json();
  return rows[0] || null;
}

async function supabaseUploadFile(dateKey, file) {
  const cleanFileName = file.name.replace(/[^a-zA-Z0-9._-]/g, "-");
  const filePath = `${dateKey}/${Date.now()}-${cleanFileName}`;
  const uploadUrl = `${SUPABASE_URL}/storage/v1/object/${STORAGE_BUCKET}/${filePath}`;

  const uploadResponse = await fetch(uploadUrl, {
    method: "POST",
    headers: supabaseHeaders({
      "Content-Type": file.type || "application/octet-stream",
      "x-upsert": "true"
    }),
    body: file
  });

  if (!uploadResponse.ok) {
    const details = await readErrorText(uploadResponse);
    throw new Error(`Could not upload file: ${details}`);
  }

  const publicUrl = `${SUPABASE_URL}/storage/v1/object/public/${STORAGE_BUCKET}/${filePath}`;

  const saveResponse = await fetch(`${SUPABASE_URL}/rest/v1/${TABLE_NAME}`, {
    method: "POST",
    headers: supabaseHeaders({
      "Content-Type": "application/json",
      Prefer: "resolution=merge-duplicates"
    }),
    body: JSON.stringify({
      [DATE_COLUMN]: dateKey,
      file_name: file.name,
      file_url: publicUrl,
      file_type: file.type || "application/octet-stream"
    })
  });

  if (!saveResponse.ok) {
    const details = await readErrorText(saveResponse);
    throw new Error(`Could not save upload record: ${details}`);
  }

  return {
    name: file.name,
    url: publicUrl,
    type: file.type || "application/octet-stream"
  };
}

async function supabaseDeleteUpload(dateKey) {
  const deleteUrl = `${SUPABASE_URL}/rest/v1/${TABLE_NAME}?${DATE_COLUMN}=eq.${dateKey}`;
  const response = await fetch(deleteUrl, {
    method: "DELETE",
    headers: supabaseHeaders({ Prefer: "return=minimal" })
  });

  if (!response.ok) {
    const details = await readErrorText(response);
    throw new Error(`Could not remove upload: ${details}`);
  }
}

function renderPreview(file) {
  if (!file) return null;

  if (file.type && file.type.startsWith("image/")) {
    return <img src={file.url} alt={file.name} className="w-full max-h-[500px] object-contain rounded-xl bg-gray-100" />;
  }

  if (file.type && file.type.startsWith("video/")) {
    return <video src={file.url} className="w-full max-h-[500px] rounded-xl bg-black" controls />;
  }

  if (file.type === "application/pdf") {
    return <iframe title={file.name} src={file.url} className="w-full h-[500px] rounded-xl border bg-white" />;
  }

  return (
    <div className="rounded-xl bg-gray-100 p-6 text-center text-gray-700">
      Preview is not available for this file type.
    </div>
  );
}

